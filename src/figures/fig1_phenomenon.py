"""
fig1_phenomenon.py — Figure 1: The Phenomenon (NeurIPS/ICML publication quality)

Panel (a): AUC + D_Σ dual-axis trajectory (Cora, 1 seed)
Panel (b): ΔAUC by method — TENT / SHOT / BN-adapt violin plot
           Uses the first dataset found in cross_method_results.csv

读取:
  cross_method_results.csv  (generated by exp_cross_method_tta.py)
  attribute_assimilation_v3.csv  (pre-existing Cora trajectory)
输出:
  fig1_phenomenon.pdf      矢量图
  fig1_phenomenon.png      光栅图
"""

import os, sys, numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import scipy.stats as ss

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from config import results_csv, figure
from style import C

# ── Global style (NeurIPS: serif, large fonts, no grid) ──────────────────────
plt.rcParams.update({
    "font.family":      "serif",
    "font.serif":       ["Times New Roman", "DejaVu Serif", "serif"],
    "font.size":        10,
    "axes.titlesize":   14,
    "axes.labelsize":   12,
    "xtick.labelsize":  10,
    "ytick.labelsize":  10,
    "legend.fontsize":  10,
    "figure.dpi":       150,
    "savefig.dpi":      300,
    "axes.linewidth":   0.8,
    "xtick.major.width": 0.6,
    "ytick.major.width": 0.6,
    "xtick.major.size":  4,
    "ytick.major.size":  4,
    "lines.linewidth":   1.8,
    "lines.markersize":  5,
    "mathtext.fontset": "stix",  # matches serif font
})

# ── Academic low-saturation colors (Seaborn colorblind) ─────────────────────
# Use C from style.py: TENT=#0173b2, SHOT=#d55e00, BN-adapt=#029e73
C_METHOD = {"TENT": C["TENT"], "SHOT": C["SHOT"], "BN-adapt": C["BN-adapt"]}


def _sig_bracket(ax, x1, x2, y, p_val, text=None):
    """
    Draw a standard significance bracket between x1 and x2 at height y.
    Horizontal bar with vertical ticks at both ends, p-value centered above.
    """
    tick_h = 0.015
    ax.plot([x1, x2], [y, y], color=".3", lw=0.8, clip_on=False)
    ax.plot([x1, x1], [y, y - tick_h], color=".3", lw=0.8, clip_on=False)
    ax.plot([x2, x2], [y, y - tick_h], color=".3", lw=0.8, clip_on=False)
    label = text if text else f"p={p_val:.2f}"
    ax.text((x1 + x2) / 2, y + 0.003, label,
            ha="center", va="bottom", fontsize=9)


# ── Load data ────────────────────────────────────────────────────────────────
df = pd.read_csv(results_csv("cross_method_results.csv"))
df["shift"] = pd.to_numeric(df["shift"], errors="coerce")
target_ds = df["dataset"].str.strip().unique()[0]

traj = pd.read_csv(results_csv("attribute_assimilation_v3.csv"))

# ── Figure ────────────────────────────────────────────────────────────────────
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.0, 2.8),
                                gridspec_kw={"wspace": 0.35})

# ══════════════════════════════════════════════════════════════════════════════
# Panel (a): Dual-axis trajectory (AUC left, D_Σ right)
# ══════════════════════════════════════════════════════════════════════════════
src_auc = traj["auc"].iloc[0]
ax1.axhline(src_auc, color=".5", lw=0.8, ls="--", alpha=0.5,
            label=f"Source / No TTA ({src_auc:.3f})")

# AUC curve (left axis)
ln1 = ax1.plot(traj["step"], traj["auc"],
               color=C_METHOD["TENT"], lw=1.8, alpha=0.9, label="AUC")[0]
ax1.set_xlabel("TTA step", fontsize=12)
ax1.set_ylabel("AUC", fontsize=12, color=C_METHOD["TENT"])
ax1.tick_params(axis="y", labelcolor=C_METHOD["TENT"])

# D_Σ curve (right axis)
ax1b = ax1.twinx()
ln2 = ax1b.plot(traj["step"], traj["D_Sigma"],
                color=C_METHOD["BN-adapt"], lw=1.5, ls=":", alpha=0.85,
                label="$D_\\Sigma$")[0]
ax1b.set_ylabel("$D_\\Sigma$", fontsize=12, color=C_METHOD["BN-adapt"])
ax1b.tick_params(axis="y", labelcolor=C_METHOD["BN-adapt"])

# ΔAUC annotation (top-right, below legend position)
delta = traj["auc"].iloc[-1] - src_auc
ax1.text(0.96, 0.12, f"ΔAUC = {delta:+.3f}",
         transform=ax1.transAxes, ha="right", va="bottom",
         fontsize=12, fontweight="bold", color=C_METHOD["TENT"])

# Merged single legend (frameoff, upper-left)
ax1.legend(handles=[ln1, ln2], loc="upper left", frameon=False,
           handlelength=1.5, fontsize=10)

# Spines: remove top, keep colored left/right
ax1.spines["top"].set_visible(False)
ax1.spines["left"].set_color(C_METHOD["TENT"])
ax1b.spines["top"].set_visible(False)
ax1b.spines["right"].set_color(C_METHOD["BN-adapt"])

# Grid: very light grey y-axis only
ax1.grid(True, axis="y", color=".85", linestyle="--", linewidth=0.3, alpha=0.2)
ax1.set_axisbelow(True)

ax1.set_title("(a) Cora, shift=0  (1 seed — placeholder)", fontsize=14, pad=6)

# ══════════════════════════════════════════════════════════════════════════════
# Panel (b): Violin plot — ΔAUC by method
# ══════════════════════════════════════════════════════════════════════════════
sub = df[(df["dataset"].str.strip() == target_ds) & (np.isclose(df["shift"], 0.0))].copy()
if len(sub) == 0:
    alt_shift = df["shift"].unique()[0]
    sub = df[(df["dataset"].str.strip() == target_ds) & (np.isclose(df["shift"], alt_shift))].copy()
    print(f"  [fig1] using shift={alt_shift} for {target_ds}")

methods = ["TENT", "SHOT", "BN-adapt"]
data_by_method = [sub[sub.method == m]["delta_AUC"].values for m in methods]

if all(len(v) > 0 for v in data_by_method):
    # Violin with smoothing
    parts = ax2.violinplot(data_by_method, positions=[1, 2, 3],
                           showmedians=True, showextrema=False,
                           bw_method=0.3)
    for pc, m in zip(parts["bodies"], methods):
        pc.set_facecolor(C_METHOD[m])
        pc.set_alpha(0.50)
        pc.set_edgecolor("none")
    parts["cmedians"].set_color(".2")
    parts["cmedians"].set_linewidth(1.0)

    # Scatter overlay (smaller, more transparent)
    for pos, m, vals in zip([1, 2, 3], methods, data_by_method):
        jitter = np.random.default_rng(42).uniform(-0.08, 0.08, size=len(vals))
        ax2.scatter(pos + jitter, vals, s=12, alpha=0.7,
                    color=C_METHOD[m], zorder=4, edgecolors="white",
                    linewidth=0.3)

    # Mean labels
    for pos, m, vals in zip([1, 2, 3], methods, data_by_method):
        y_off = 0.02 * (vals.max() - vals.min()) if vals.max() > vals.min() else 0.01
        ax2.text(pos, vals.min() - y_off, f"{np.mean(vals):.3f}",
                 ha="center", va="top", fontsize=9, color=C_METHOD[m],
                 fontweight="bold")

    ax2.axhline(0, color=".3", lw=0.8, ls="--", alpha=0.5)

    # Significance brackets (manual, no floating text)
    u_ts, p_ts = ss.mannwhitneyu(data_by_method[0], data_by_method[1])
    u_bt, p_bt = ss.mannwhitneyu(data_by_method[2], data_by_method[0])

    ymin, ymax = ax2.get_ylim()
    y_range = ymax - ymin
    ax2.set_ylim(ymin - 0.28 * y_range, ymax)

    # Bracket: TENT vs SHOT
    _sig_bracket(ax2, 1, 2, ymin - 0.05 * y_range, p_ts)

    # Bracket: BN-adapt vs TENT
    _sig_bracket(ax2, 2.9, 3.1, ymin - 0.05 * y_range, p_bt)

ax2.set_xticks([1, 2, 3])
ax2.set_xticklabels(methods, fontsize=11)
ax2.set_ylabel("ΔAUC (relative to source)", fontsize=12)
ax2.set_title(f"(b) {target_ds}, shift={sub['shift'].iloc[0]:.1f}, 5 seeds",
              fontsize=14, pad=6)

# Panel (b) style: remove top/right spines, light grid
ax2.spines["top"].set_visible(False)
ax2.spines["right"].set_visible(False)
ax2.spines["left"].set_linewidth(0.8)
ax2.spines["bottom"].set_linewidth(0.8)
ax2.tick_params(width=0.6)
ax2.grid(True, axis="y", color=".85", linestyle="--", linewidth=0.3, alpha=0.2)
ax2.set_axisbelow(True)

# ── Save ──────────────────────────────────────────────────────────────────────
fig.savefig(figure("fig1_phenomenon.pdf"), dpi=300, bbox_inches="tight")
fig.savefig(figure("fig1_phenomenon.png"), dpi=300, bbox_inches="tight")
plt.close(fig)
print("Saved fig1_phenomenon.pdf + .png")